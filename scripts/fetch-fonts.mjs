/**
 * One-off script: pull the woff2 files for our three type families from Google Fonts
 * and self-host them under `public/fonts`, emitting `src/app/fonts.css`.
 *
 * Run with: node scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT_FONTS = path.join(process.cwd(), "public", "fonts");
const OUT_CSS = path.join(process.cwd(), "src", "app", "fonts.css");

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0 Safari/537.36";

/** Only the subsets we actually serve. */
const SUBSETS = new Set(["arabic", "latin", "latin-ext"]);

const FAMILIES = [
  { query: "Cairo:wght@200..1000", slug: "cairo" },
  { query: "Amiri+Quran", slug: "amiri-quran" },
  { query: "Inter:wght@100..900", slug: "inter" },
  { query: "Geist+Mono:wght@100..900", slug: "geist-mono" },
];

async function main() {
  await mkdir(OUT_FONTS, { recursive: true });
  const blocks = [];

  for (const family of FAMILIES) {
    const url = `https://fonts.googleapis.com/css2?family=${family.query}&display=swap`;
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`${url} -> ${res.status}`);
    const css = await res.text();

    // Google emits: /* subset */ @font-face { ... unicode-range: ...; }
    const parts = css.split("/*").slice(1);
    for (const part of parts) {
      const subset = part.slice(0, part.indexOf("*/")).trim();
      const body = part.slice(part.indexOf("@font-face"));
      const end = body.indexOf("}");
      const face = body.slice(0, end);
      if (!SUBSETS.has(subset)) continue;

      const srcMatch = face.match(/url\((https:[^)]+\.woff2)\)/);
      if (!srcMatch?.[1]) continue;
      const fontUrl = srcMatch[1];
      const fileName = `${family.slug}-${subset}.woff2`;

      const bin = await fetch(fontUrl, { headers: { "User-Agent": UA } });
      if (!bin.ok) throw new Error(`${fontUrl} -> ${bin.status}`);
      await writeFile(path.join(OUT_FONTS, fileName), Buffer.from(await bin.arrayBuffer()));

      blocks.push(
        `${face
          .replace(/src: url\([^)]+\)/, `src: url("/fonts/${fileName}")`)
          .replace(/^\s+|\s+$/gm, "  ")
          .trim()}\n}`,
      );
      console.log(`downloaded ${fileName}`);
    }
  }

  const css = `/* Generated by scripts/fetch-fonts.mjs — do not edit by hand. */\n${blocks.join("\n\n")}\n`;
  await writeFile(OUT_CSS, css);
  console.log(`\nwrote ${path.relative(process.cwd(), OUT_CSS)} with ${blocks.length} faces`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
